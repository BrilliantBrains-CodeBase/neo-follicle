// Gallery image pipeline -- turns the backup's WordPress originals into the
// assets /image-gallery/ serves.
//
// Re-runnable, and it wipes public/image-gallery/ first: nothing in there is
// hand-edited. Edit scripts/gallery-assets.mjs or this file, then
// `npm run gen:galleryimg`.
//
// Modelled on gen-treatment-images.mjs and it keeps that file's central rule:
// NEVER CROP, NEVER UPSCALE. Most sources here are before/after pairs
// composited side by side in one file, several with captions burned in, so a
// `fit: 'cover'` crop to some target ratio silently cuts off half the
// comparison -- which is worse than serving an odd ratio.
//
// Two things this does that the treatment pipeline does not:
//
//   1. TWO DERIVATIVES PER IMAGE. The treatment pages show one size; this page
//      shows a grid tile AND, on click, a full-size view in the lightbox.
//      Measured across these 82 files, full-size-only costs 4.1MB with a 140KB
//      tile for every 1280x1280 R*_BF_* file. Thumbs at 600w bring the grid to
//      ~1.6MB and the full files are never fetched until a lightbox opens.
//      600w covers the tile's ~380 CSS px at lg:grid-cols-3 and ~320 px on
//      mobile at 1.5-1.9x DPR.
//
//   2. IT WRITES THE DIMENSIONS INTO THE CONTENT MODULE. gen-treatment-images
//      emits public/treatments/sizes.json, but nothing imports it -- the data
//      modules hard-code 650x450, which works only because every treatment
//      source happens to be that size. These are not uniform: 650x450 (54),
//      1280x1280 (20), 512x512 (5) and 1024x1024 (3). Guessing is not an
//      option, so the generated TS carries real width/height per derivative.
//      sizes.json is still written, for verify-gallery.mjs to cross-check.
//
// NOTE: this does NOT touch public/gallery/, which holds six ad-hoc files the
// home page's TreatmentGallery depends on and which have no generator. Pointing
// this script at that directory would wipe them.
import fs from 'node:fs'
import path from 'node:path'
import sharp from 'sharp'
import { resolveUpload, root } from './blog-assets.mjs'
import { GALLERY_SECTIONS, galleryImagePath } from './gallery-assets.mjs'

const outDir = path.join(root, 'public/image-gallery')
const contentFile = path.join(root, 'src/content/gallery/image-gallery.generated.ts')

const FULL = { width: 1200, quality: 78 }
const THUMB = { width: 600, quality: 72 }

const written = []
async function write(servedPath, src, { width, quality }) {
  const file = path.join(root, 'public', servedPath.replace(/^\//, ''))
  fs.mkdirSync(path.dirname(file), { recursive: true })
  const out = await sharp(src)
    .resize(width, null, { withoutEnlargement: true })
    .webp({ quality })
    .toFile(file)
  written.push({ file: servedPath, size: out.size })
  return { src: servedPath, width: out.width, height: out.height }
}

fs.rmSync(outDir, { recursive: true, force: true })

const sizes = {}
const bySection = {}
let flagged = 0

for (const section of GALLERY_SECTIONS) {
  if (section.review) flagged++
  const items = []
  for (const [i, entry] of section.images.entries()) {
    // Two source kinds, documented on `u()` and `f()` in gallery-assets.mjs:
    // `from` is a capture of the old site, `file` is a client delivery sitting
    // in the repo. Everything after this line is identical for both.
    const src = entry.file ? path.join(root, entry.file) : resolveUpload(`/${entry.from}`)
    if (entry.file && !fs.existsSync(src)) throw new Error(`missing client file: ${entry.file}`)
    const n = i + 1
    const thumb = await write(galleryImagePath(section.id, n, 'thumb'), src, THUMB)
    const full = await write(galleryImagePath(section.id, n, 'full'), src, FULL)
    sizes[thumb.src] = { width: thumb.width, height: thumb.height }
    sizes[full.src] = { width: full.width, height: full.height }
    items.push({ thumb, full, alt: entry.alt, caption: entry.caption })
  }
  bySection[section.id] = items
}

fs.mkdirSync(outDir, { recursive: true })
fs.writeFileSync(path.join(outDir, 'sizes.json'), `${JSON.stringify(sizes, null, 2)}\n`)

/* ---- the committed content module ------------------------------------------ */
const d = (x) => `{ src: '${x.src}', width: ${x.width}, height: ${x.height} }`
const body = Object.entries(bySection)
  .map(([id, items]) => {
    const rows = items
      .map((it) => {
        const caption = it.caption ? `,\n      caption: ${JSON.stringify(it.caption)}` : ''
        return (
          `    {\n      thumb: ${d(it.thumb)},\n      full: ${d(it.full)},\n` +
          `      alt: ${JSON.stringify(it.alt)}${caption},\n    },`
        )
      })
      .join('\n')
    return `  '${id}': [\n${rows}\n  ],`
  })
  .join('\n')

fs.mkdirSync(path.dirname(contentFile), { recursive: true })
fs.writeFileSync(
  contentFile,
  `// GENERATED by scripts/gen-gallery-images.mjs. Do not edit by hand.\n` +
    `//\n` +
    `// Sources and alt text live in scripts/gallery-assets.mjs; dimensions are\n` +
    `// measured from the files sharp actually wrote. Regenerate with\n` +
    `// \`npm run gen:galleryimg\`.\n` +
    `import type { GalleryImage } from './types'\n\n` +
    `export const GALLERY_IMAGES: Record<string, GalleryImage[]> = {\n${body}\n}\n`,
)

/* ---- report ----------------------------------------------------------------- */
const total = written.reduce((a, w) => a + w.size, 0)
const thumbs = written.filter((w) => w.file.endsWith('-thumb.webp'))
const fulls = written.filter((w) => w.file.endsWith('-full.webp'))
const sum = (xs) => xs.reduce((a, w) => a + w.size, 0)
const kb = (b) => `${(b / 1024).toFixed(0)}KB`

console.log(`\ngen-gallery-images: ${written.length} files, ${(total / 1024 / 1024).toFixed(1)}MB`)
console.log(`  ${thumbs.length} thumbs  ${kb(sum(thumbs))}  (largest ${kb(Math.max(...thumbs.map((w) => w.size)))})`)
console.log(`  ${fulls.length} full    ${kb(sum(fulls))}  (largest ${kb(Math.max(...fulls.map((w) => w.size)))})`)
console.log(`  -> ${path.relative(root, contentFile)}`)
if (flagged) console.log(`  ${flagged} sections flagged for review in gallery-assets.mjs`)
