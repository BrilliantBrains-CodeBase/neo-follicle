// Press clipping pipeline -- turns the scans in content/media/clippings/ into
// the two derivatives the "In the Press" band on /our-blogs/ serves.
//
// Re-runnable, and it wipes public/media/ first: nothing in there is
// hand-edited. Drop a new scan into content/media/clippings/, add its entry to
// src/content/media/coverage.ts, then `npm run gen:mediaimg`.
//
// Most of the 27 placements in the coverage report are links to other people's
// websites and have no image at all. Only the print ones do -- eSanje and
// Happiest Health -- and a clipping is a photograph of a page, so it wants the
// same treatment a gallery photograph gets: a small tile in the list and a
// full-size view on click.
//
// FULL/THUMB are gen-gallery-images.mjs's constants, deliberately identical, so
// a clipping behaves in Lightbox exactly as a gallery image does. NEVER CROP,
// NEVER UPSCALE, for the reason that file gives at greater length: a clipping
// is a whole printed page, and a `fit: 'cover'` crop to some target ratio would
// cut the headline or the masthead off the one image whose entire value is
// being legible.
//
// The directory IS the manifest -- with a handful of files there is nothing for
// a scripts/media-assets.mjs to hold that the filenames do not. Alt text and
// captions live beside their entry in src/content/media/coverage.ts, matching
// the split src/content/gallery/types.ts documents: generated modules carry
// sources and dimensions, authored modules carry sentences.
//
// Deliberately NOT added to scripts/gallery-assets.mjs: verify-gallery.mjs
// asserts every asset that manifest generates is referenced by /image-gallery/
// or /video-gallery/, and a press clipping is referenced by neither.
import fs from 'node:fs'
import path from 'node:path'
import sharp from 'sharp'
import { root } from './blog-assets.mjs'

const sourceDir = path.join(root, 'content/media/clippings')
const outDir = path.join(root, 'public/media')
const contentFile = path.join(root, 'src/content/media/clippings.generated.ts')

const FULL = { width: 1200, quality: 78 }
const THUMB = { width: 600, quality: 72 }

const written = []
async function write(servedPath, src, { width, quality }) {
  const file = path.join(root, 'public', servedPath.replace(/^\//, ''))
  fs.mkdirSync(path.dirname(file), { recursive: true })
  const out = await sharp(src).resize(width, null, { withoutEnlargement: true }).webp({ quality }).toFile(file)
  written.push({ file: servedPath, size: out.size })
  return { src: servedPath, width: out.width, height: out.height }
}

const slugs = fs
  .readdirSync(sourceDir)
  .filter((f) => /\.(jpe?g|png|webp)$/i.test(f))
  .sort()

if (slugs.length === 0) throw new Error(`no clippings in ${path.relative(root, sourceDir)}`)

fs.rmSync(outDir, { recursive: true, force: true })

const clippings = {}
for (const file of slugs) {
  const slug = file.replace(/\.\w+$/, '')
  const src = path.join(sourceDir, file)
  clippings[slug] = {
    thumb: await write(`/media/${slug}-thumb.webp`, src, THUMB),
    full: await write(`/media/${slug}-full.webp`, src, FULL),
  }
}

/* ---- the committed content module ------------------------------------------ */
const d = (x) => `{ src: '${x.src}', width: ${x.width}, height: ${x.height} }`
const body = Object.entries(clippings)
  .map(([slug, { thumb, full }]) => `  '${slug}': {\n    thumb: ${d(thumb)},\n    full: ${d(full)},\n  },`)
  .join('\n')

fs.mkdirSync(path.dirname(contentFile), { recursive: true })
fs.writeFileSync(
  contentFile,
  `// GENERATED by scripts/gen-media-images.mjs. Do not edit by hand.\n` +
    `//\n` +
    `// One entry per scan in content/media/clippings/, keyed by filename. Alt\n` +
    `// text and captions are authored in ./coverage.ts. Regenerate with\n` +
    `// \`npm run gen:mediaimg\`.\n` +
    `import type { Derivative } from '../gallery/types'\n\n` +
    `export type ClippingDerivatives = { thumb: Derivative; full: Derivative }\n\n` +
    `export const CLIPPINGS: Record<string, ClippingDerivatives> = {\n${body}\n}\n`,
)

/* ---- report ----------------------------------------------------------------- */
const kb = (b) => `${(b / 1024).toFixed(0)}KB`
console.log(`gen-media-images: ${written.length} files from ${slugs.length} clipping(s) -> public/media/`)
for (const w of written) console.log(`  ${kb(w.size).padStart(7)}  ${w.file}`)
console.log(`  -> ${path.relative(root, contentFile)}`)
