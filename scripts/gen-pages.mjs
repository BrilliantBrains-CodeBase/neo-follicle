import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const ts = fs.readFileSync(path.join(root, 'src/seo/pages.ts'), 'utf8')
const m = ts.match(/export const pages: PageSeo\[\] = (\[[\s\S]*?\n\])\n\nexport const pageBySlug/)
const pages = JSON.parse(m[1])

const pascal = (s) =>
  s.split(/[^a-zA-Z0-9]+/).filter(Boolean)
   .map((w) => w[0].toUpperCase() + w.slice(1))
   .join('')

// A slug can start with a digit in theory; none do, but guard anyway.
const compName = (s) => { const n = pascal(s); return /^[0-9]/.test(n) ? 'Page' + n : n }

const MARKER = '// GENERATED by scripts/gen-pages.mjs. Do not edit by hand.'

const stub = (slug) =>
`${MARKER}
import PagePlaceholder from '../components/PagePlaceholder'

export default function ${compName(slug)}() {
  return <PagePlaceholder slug="${slug}" />
}
`

/** The stub shape this script emitted before it wrote a marker. */
const legacyStub = (slug) =>
`import PagePlaceholder from '../components/PagePlaceholder'

export default function ${compName(slug)}() {
  return <PagePlaceholder slug="${slug}" />
}
`

// Every `type: 'post'` slug is a blog post, and they all share one layout. The
// layout lives in src/components/BlogPost.tsx and the copy in src/content/posts/,
// so the page file is just the binding between the two. Importing the record
// here rather than looking it up in a shared registry is what keeps each
// article body in its own chunk -- see src/routeView.tsx.
const postPage = (slug) =>
`${MARKER}
import BlogPost from '../components/BlogPost'
import post from '../content/posts/${slug}'

export default function ${compName(slug)}() {
  return <BlogPost post={post} />
}
`

const template = (p) => (p.type === 'post' ? postPage(p.slug) : stub(p.slug))

const pagesDir = path.join(root, 'src/pages')
const written = []
const skipped = []

for (const p of pages) {
  const file = path.join(pagesDir, `${p.slug}.tsx`)
  const next = template(p)

  // Only ever overwrite a file this script wrote. Anything else is authored --
  // home.tsx, our-blogs.tsx, uncategorized.tsx and whatever comes next -- and
  // regenerating used to destroy it silently, because there was no guard here
  // at all.
  //
  // The marker is what makes a file ours, rather than an exact match against
  // the current template: otherwise changing a template would lock this script
  // out of the very files it wrote. `legacyStub` recognises the pages generated
  // before the marker existed, and can go once they have all been rewritten.
  if (fs.existsSync(file)) {
    const current = fs.readFileSync(file, 'utf8')
    if (current === next) continue
    if (!current.startsWith(MARKER) && current !== legacyStub(p.slug)) {
      skipped.push(p.slug)
      continue
    }
  }

  fs.writeFileSync(file, next)
  written.push(p.slug)
}

// Route table: one import per page, ordered by slug for a stable diff.
const sorted = [...pages].sort((a, b) => a.slug.localeCompare(b.slug))
// Blog posts are split out: each one carries its own article body, and a static
// import would put all 19 in the entry chunk that every page downloads. See
// src/routeView.tsx.
const isSplit = (p) => p.type === 'post'

const imports = sorted
  .filter((p) => !isSplit(p))
  .map((p) => `import ${compName(p.slug)} from './pages/${p.slug}'`)
  .join('\n')
const routes = sorted
  .map((p) =>
    isSplit(p)
      ? `  { path: '${p.path}', load: () => import('./pages/${p.slug}'), slug: '${p.slug}' },`
      : `  { path: '${p.path}', element: <${compName(p.slug)} />, slug: '${p.slug}' },`,
  )
  .join('\n')

fs.writeFileSync(path.join(root, 'src/routes.tsx'),
`// GENERATED by scripts/gen-pages.mjs. Do not edit by hand.
// Regenerate with: npm run gen:pages
//
// One route per URL in src/seo/pages.ts, so a route can never drift from its
// SEO record. Paths keep their trailing slash -- that is P0-PRESERVE.
import type { ComponentType, ReactElement } from 'react'
import Layout from './components/Layout'
import NotFound from './pages/not-found'
${imports}

/**
 * A route is either eager, carrying an element, or split, carrying a loader.
 * The blog posts are split -- see src/routeView.tsx for why, and for how the
 * module is awaited before render.
 */
export type AppRoute = {
  path: string
  slug: string
  element?: ReactElement
  load?: () => Promise<{ default: ComponentType }>
}

export const appRoutes: AppRoute[] = [
${routes}
]

export { Layout, NotFound }
`)

console.log(`gen-pages: ${written.length} page components written, ${skipped.length} authored files left alone`)
if (skipped.length) console.log(`           kept: ${skipped.join(', ')}`)
console.log(`           ${pages.length} routes -> src/routes.tsx`)
