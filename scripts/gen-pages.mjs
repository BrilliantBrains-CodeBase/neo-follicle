import fs from 'node:fs'
import path from 'node:path'

const root = '/Users/d1/neofollicle'
const ts = fs.readFileSync(path.join(root, 'src/seo/pages.ts'), 'utf8')
const m = ts.match(/export const pages: PageSeo\[\] = (\[[\s\S]*?\n\])\n\nexport const pageBySlug/)
const pages = JSON.parse(m[1])

const pascal = (s) =>
  s.split(/[^a-zA-Z0-9]+/).filter(Boolean)
   .map((w) => w[0].toUpperCase() + w.slice(1))
   .join('')

// A slug can start with a digit in theory; none do, but guard anyway.
const compName = (s) => { const n = pascal(s); return /^[0-9]/.test(n) ? 'Page' + n : n }

const pagesDir = path.join(root, 'src/pages')
for (const p of pages) {
  const file = path.join(pagesDir, `${p.slug}.tsx`)
  fs.writeFileSync(file,
`import PagePlaceholder from '../components/PagePlaceholder'

export default function ${compName(p.slug)}() {
  return <PagePlaceholder slug="${p.slug}" />
}
`)
}

// Route table: one import per page, ordered by slug for a stable diff.
const sorted = [...pages].sort((a, b) => a.slug.localeCompare(b.slug))
const imports = sorted.map((p) => `import ${compName(p.slug)} from './pages/${p.slug}'`).join('\n')
const routes = sorted
  .map((p) => `  { path: '${p.path}', element: <${compName(p.slug)} />, slug: '${p.slug}' },`)
  .join('\n')

fs.writeFileSync(path.join(root, 'src/routes.tsx'),
`// GENERATED by scripts/gen-pages.mjs. Do not edit by hand.
// Regenerate with: npm run gen:pages
//
// One route per URL in src/seo/pages.ts, so a route can never drift from its
// SEO record. Paths keep their trailing slash -- that is P0-PRESERVE.
import type { ReactElement } from 'react'
import Layout from './components/Layout'
import NotFound from './pages/not-found'
${imports}

export type AppRoute = { path: string; element: ReactElement; slug: string }

export const appRoutes: AppRoute[] = [
${routes}
]

export { Layout, NotFound }
`)

console.log(`gen-pages: ${pages.length} page components -> src/pages/`)
console.log(`           ${pages.length} routes -> src/routes.tsx`)
